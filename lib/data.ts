/**
 * Generate a clean, SEO-friendly, deterministic URL slug for a product
 */
export function getProductSlug(product: Product): string {
  const base = product.name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return `${base}-${product.id}`;
}

/**
 * Lookup a product by its URL slug
 */
export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS_DATA.find((p) => getProductSlug(p) === slug);
}

